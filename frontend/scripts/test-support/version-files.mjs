/*
 * The seven files that carry the app's version, written into a gate repo, for
 * check-version-sync.test.mjs and bump-version.test.mjs. Each one holds a
 * lookalike next to the version that counts: a dependency version in the
 * Cargo manifest and in both lockfiles, the parent version in the pom.
 *
 * `versions` overrides one file at a time; everything else is 1.2.3.
 */
export function seedVersionFiles(repo, versions = {}) {
	const v = {
		pkg: '1.2.3',
		lock: '1.2.3',
		lockRoot: '1.2.3',
		tauri: '1.2.3',
		clientTs: '1.2.3',
		cargo: '1.2.3',
		cargoLock: '1.2.3',
		pom: '1.2.3',
		...versions
	};
	repo.write('frontend/package.json', JSON.stringify({ name: 'f', version: v.pkg }, null, '\t'));
	repo.write(
		'frontend/package-lock.json',
		JSON.stringify(
			{
				name: 'f',
				version: v.lock,
				lockfileVersion: 3,
				requires: true,
				packages: {
					'': { name: 'f', version: v.lockRoot, dependencies: { dep: '^1.0.0' } },
					'node_modules/dep': { version: '1.0.0' }
				}
			},
			null,
			'\t'
		)
	);
	// A dependency sorts ahead of the project and carries the version the
	// other files agree on, so reading the first entry would always pass.
	repo.write(
		'frontend/src-tauri/Cargo.lock',
		[
			'# This file is automatically @generated by Cargo.',
			'version = 4',
			'',
			'[[package]]',
			'name = "aaa-dep"',
			'version = "1.2.3"',
			'',
			'[[package]]',
			'name = "app"',
			`version = "${v.cargoLock}"`,
			'dependencies = [',
			' "aaa-dep",',
			']',
			''
		].join('\n')
	);
	repo.write(
		'frontend/src-tauri/tauri.conf.json',
		JSON.stringify({ version: v.tauri }, null, '\t')
	);
	repo.write('frontend/src/lib/version.ts', `export const CLIENT_VERSION = '${v.clientTs}';\n`);
	repo.write(
		'frontend/src-tauri/Cargo.toml',
		[
			'[package]',
			'name = "app"',
			`version = "${v.cargo}"`,
			'',
			'[dependencies]',
			'serde = { version = "9.9.9" }',
			''
		].join('\n')
	);
	repo.write(
		'backend/pom.xml',
		[
			'<project>',
			'  <parent>',
			'    <groupId>org.springframework.boot</groupId>',
			'    <artifactId>spring-boot-starter-parent</artifactId>',
			'    <version>4.0.0</version>',
			'  </parent>',
			'  <groupId>org.voxrox</groupId>',
			'  <artifactId>mail-backend</artifactId>',
			`  <version>${v.pom}</version>`,
			'</project>',
			''
		].join('\n')
	);
}
